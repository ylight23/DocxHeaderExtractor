using System.Text;
using System.Text.Json;
using DocxHeaderExtractor.V5Qualification.P7;

// D3.1 protocol snapshot candidate (offline). Writes the manifest of every hash and the candidate document from the same constants the
// tests use, so the document and the code cannot drift apart. No network call. Nothing here freezes the snapshot.
internal static class D31Snapshot
{
    const string Tag = "alibaba";
    const int MaxTokens = 32768;   // visible 16384 plus the assumed reasoning reserve; not verified at the endpoint (gate T)

    public static void Run(string repoRoot)
    {
        var art = Path.Combine(repoRoot, "artifacts", "web-pdf-semantic-diagnostic");
        var manifest = P7F1V6Protocol.Manifest(Tag, MaxTokens);
        var manifestJson = JsonSerializer.Serialize(manifest, new JsonSerializerOptions { WriteIndented = true });
        File.WriteAllText(Path.Combine(art, "p7.f1.v6.d3.1-protocol-manifest.v1.json"), manifestJson + "\n", new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(art, "p7.f1.v6.d3.1-protocol-snapshot.candidate.md"), Document(manifestJson), new UTF8Encoding(false));
        Console.WriteLine("wrote manifest and candidate document");
    }

    static string Document(string manifestJson)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# V6 D3.1: protocol snapshot, candidate (Issue #9), offline");
        sb.AppendLine();
        sb.AppendLine("Written for: the Issue #9 reviewers, to review before any freeze.");
        sb.AppendLine("Status: CANDIDATE FOR REVIEW. Not frozen. No inference call. No Gold or production change.");
        sb.AppendLine("Baseline commit: da9a3e0 (route lock). Model `qwen/qwen3.7-flash`, route `alibaba`, input budget 131,072 bytes (internal cap).");
        sb.AppendLine();
        sb.AppendLine("This document is generated by `scripts/P7F1Q` mode `d31-snapshot` from the constants in `P7F1V6Protocol.cs`. Do not edit it by hand.");
        sb.AppendLine();
        sb.AppendLine("## 1. Responsibilities");
        sb.AppendLine("- Qwen decides every semantic question: whether a line is a heading, its level, its parent, and whether two lines continue one heading. The prompts never define a heading.");
        sb.AppendLine("- C# does transport, identifiers, budgets, provenance and the validity of the protocol. It never selects a line, derives a hierarchy, or resolves a conflict.");
        sb.AppendLine("- Interpretation comes first (D1 contract `P7_F1_V6_INTERPRET_V1`). A reply that is not COMPLETE stops the run with its own status, and the status, reason and open questions are kept.");
        sb.AppendLine();
        sb.AppendLine("## 2. Request contract (OpenRouter chat completions)");
        sb.AppendLine("The envelope is built by `P7F1V6Protocol.Envelope`. Every field is fixed in code; the adapter chooses none of them.");
        sb.AppendLine();
        sb.AppendLine("| Field | Value |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| `model` | `{P7F1V6Protocol.ChatModel}` |");
        sb.AppendLine("| `messages` | exactly two: `system` (platform rules, then the node-kind rules) and `user` (the node payload, as UTF-8 JSON text) |");
        sb.AppendLine("| `response_format` | `{\"type\":\"json_object\"}` |");
        sb.AppendLine("| `temperature` | `0` |");
        sb.AppendLine($"| `max_tokens` | `{MaxTokens}` (candidate; gate T may change it) |");
        sb.AppendLine("| `provider` | `{\"only\":[\"alibaba\"],\"allow_fallbacks\":false,\"require_parameters\":true}` |");
        sb.AppendLine("| `tools`, `tool_choice` | absent. Forced tool calling is not used; the endpoint does not support `required` or `function`. Retrieval is a RETRIEVE status in the JSON reply. |");
        sb.AppendLine("| `reasoning` | absent until gate T fixes its mode and accounting |");
        sb.AppendLine();
        sb.AppendLine("## 3. System prompts (verbatim from the code)");
        sb.AppendLine();
        sb.AppendLine("### 3.1 Platform rules (shared by every node)");
        sb.AppendLine("```text");
        sb.AppendLine(P7F1V6Protocol.PlatformPrompt);
        sb.AppendLine("```");
        sb.AppendLine();
        foreach (var kind in new[] { P7F1V6Hier.Kind.Local, P7F1V6Hier.Kind.Reconcile, P7F1V6Hier.Kind.Synthesis, P7F1V6Hier.Kind.Global })
        {
            sb.AppendLine($"### 3.{(int)kind + 2} Node kind {kind.ToString().ToUpperInvariant()}");
            sb.AppendLine("The system message is the platform rules, a blank line, then this text.");
            sb.AppendLine("```text");
            sb.AppendLine(P7F1V6Protocol.KindPrompts[kind]);
            sb.AppendLine("```");
            sb.AppendLine();
        }
        sb.AppendLine("### 3.6 Interpretation request");
        sb.AppendLine("```text");
        sb.AppendLine(P7F1V6Protocol.InterpretPrompt);
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("## 4. Node response schema (`P7_F1_V6_HIER_NODE_V3`, documented; enforced by the parser)");
        sb.AppendLine("```json");
        sb.AppendLine(P7F1V6Protocol.NodeResponseSchema);
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("The parser refuses: unknown or missing root keys, a `\\u` escape anywhere, a status outside the enum, a revision of an id the node was not given, a duplicate id, an evidence reference that was not shown, a parent or continuation that was not shown, an unconfirmed shown id, and a RETRIEVE reply that carries items. Each refusal is recorded with its code.");
        sb.AppendLine();
        sb.AppendLine("## 5. Payloads");
        sb.AppendLine("Every node payload carries: `protocolVersion`, `nodeId`, `kind`, `level`, `instruction` (the user's text, verbatim), `instructionSha256`, `interpretation` and `interpretationSha256` (the agreed reading returned by Qwen), `manifest`, `overview`, and the node's lines. Source text is a JSON string value. Layout is present only where `layoutEvidence` is PRESENT; a synthesis or global node sees `AVAILABLE_ON_REOPEN` and must reopen an id to receive it.");
        sb.AppendLine();
        sb.AppendLine("## 6. Hashes (manifest)");
        sb.AppendLine("The manifest is generated from the same constants. The regression test in `P7F1V6ProtocolD31Tests` compares the committed manifest with a fresh computation, so any change to a prompt, schema or envelope field changes a hash and fails the test until the manifest is regenerated and reviewed.");
        sb.AppendLine();
        sb.AppendLine("```json");
        sb.AppendLine(manifestJson);
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("Per-request hashes are recorded at run time: the system message SHA-256, the payload SHA-256 (already in the raw store), the serialized envelope SHA-256, and the response SHA-256. They are not known until a request is made, so they are not in this manifest.");
        sb.AppendLine();
        sb.AppendLine("## 7. Fixtures and offline regression");
        sb.AppendLine("`artifacts/web-pdf-semantic-diagnostic/p7.f1.v6.d3.1-fixtures/` holds one JSON file per contract case. Each names the node it applies to, the expected outcome, and a response template. The test substitutes the identifiers of the payload it receives, sends the response through the real parser, and checks the outcome. Fixtures are not scripted decisions: they test the protocol's acceptance rules only.");
        sb.AppendLine();
        sb.AppendLine("Covered by tests: the user's instruction is kept verbatim; a line of source text that reads like an instruction stays inside the user message as data; the system message never changes with the source; the request envelope has exactly two roles and the locked provider block; retrieval alone changes no decision; an incomplete reply changes nothing; a non-COMPLETE interpretation stops the run and keeps its reason and questions.");
        sb.AppendLine();
        sb.AppendLine("### 7.1 What the injection tests show, and what they do not");
        sb.AppendLine("The tests show that the protocol packages source text as data: it sits in a JSON string inside the user message, and the system message never changes with the source. They do not show that Qwen resists prompt injection. Only a provider run can test that, and none is authorised by this document.");
        sb.AppendLine();
        sb.AppendLine("## 7.2 Heading levels");
        sb.AppendLine("When the instruction asks for levels or a hierarchy, Qwen gives `level` (integer 1 to 9) for every SELECT. Level is allowed only with SELECT. The program never infers a level from typography, numbering or position. `parentId` and `continuesFromId` are relations between shown ids, not levels.");
        sb.AppendLine();
        sb.AppendLine("## 7.3 Reasons from nodes that do not complete");
        sb.AppendLine("A node that replies INCOMPLETE, CLARIFICATION_REQUIRED or NOT_ANSWERABLE must give a reason; CLARIFICATION_REQUIRED must also give at least one openQuestions entry. Reason and openQuestions are refused on COMPLETE and RETRIEVE. The run keeps each reason, its questions and the raw response hash.");
        sb.AppendLine();
        sb.AppendLine("## 7.4 Request template fingerprint");
        sb.AppendLine("`requestTemplateSha256` pins every envelope field except the system message and the user payload: model, roles, response format, temperature, max_tokens, and the provider block. A test changes each field in turn and expects the fingerprint to change.");
        sb.AppendLine();
        sb.AppendLine("## 7.5 Request size");
        sb.AppendLine("The input budget of 131,072 bytes applies to the user payload. The preflight reports the largest serialized request envelope (`maxEnvelopeBytes`), which adds the system message and JSON escaping. The envelope is not capped separately yet; that is a decision for the reviewer.");
        sb.AppendLine();
        sb.AppendLine("## 8. Not decided here (gates still open)");
        sb.AppendLine("- Gate T: reasoning mode, reserve inside `max_tokens`, usage accounting, tokenizer or sourced measurement, timeout, and the retry policy (zero by default).");
        sb.AppendLine("- Gate S: raw directory ACL, redaction, retention, and the route's data policy.");
        sb.AppendLine("- The USD ceiling for C1, proposed after gate T. Cost bounds: `p7.f1.v6.d3-cost-bound.v1.json`, route `alibaba`.");
        sb.AppendLine("- A live check of the request on the endpoint. None has been made, and none is authorised by this document.");
        sb.AppendLine();
        sb.AppendLine("## 9. What a reviewer should check before freeze");
        sb.AppendLine("1. The platform rules do not define heading, level or hierarchy, and do not tell Qwen which answer is expected.");
        sb.AppendLine("2. The source-as-data rule covers every place where source text can appear (owned, context, shown, search results, reopened lines, pair observations).");
        sb.AppendLine("3. Each node kind's authority matches the table in `p7.f1.v6.d2-design.v1.md`.");
        sb.AppendLine("4. The envelope is what you want sent to the endpoint, with `allow_fallbacks` false.");
        sb.AppendLine("5. The fixtures cover the refusal codes you expect, and the manifest hashes are the ones you approve.");
        return sb.ToString();
    }
}

using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace IdentityBenchmarkV4HB;

internal static class Program
{
    private const string AdjudicationRoot = "artifacts/identity-benchmark/v4/semantic-adjudication";
    private const string ResultsRelative = AdjudicationRoot + "/results";
    private const int ExpectedCount = 128;

    public static int Main(string[] args)
    {
        var root = Path.GetFullPath(args.FirstOrDefault(x => !x.StartsWith("--", StringComparison.Ordinal)) ?? Directory.GetCurrentDirectory());
        try
        {
            var command = args.FirstOrDefault(x => x.StartsWith("--", StringComparison.Ordinal)) ?? "--init";
            return command switch
            {
                "--init" => Initialize(root),
                "--validate" => Validate(root, args.SkipWhile(x => x != "--validate").Skip(1).FirstOrDefault()),
                "--freeze" => Freeze(root, args.SkipWhile(x => x != "--freeze").Skip(1).FirstOrDefault()),
                _ => Fail("V4H_B_UNKNOWN_COMMAND"),
            };
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"V4H_B_ERROR={ex.Message}");
            return 2;
        }
    }

    private static int Initialize(string root)
    {
        var bindings = LoadBindings(root);
        var output = Full(root, ResultsRelative);
        Directory.CreateDirectory(output);
        var progressPath = Path.Combine(output, "review-progress.json");
        if (File.Exists(Path.Combine(output, "human-adjudication.frozen.v1.json"))) return Fail("V4H_B_ALREADY_FROZEN");
        if (File.Exists(progressPath) || File.Exists(Path.Combine(output, "human-adjudication.responses.json")))
        {
            Console.WriteLine("STATUS=V4H_ADJUDICATION_PROGRESS_ALREADY_EXISTS NO_WRITE=true");
            return 0;
        }

        WriteJson(progressPath, new
        {
            schemaVersion = "a99-v4h-b-review-progress-v1",
            status = "V4H_ADJUDICATION_INCOMPLETE",
            gate = "AWAITING_HUMAN_INPUT",
            reviewPackManifest = AdjudicationRoot + "/review-item-manifest.json",
            reviewPackManifestSha256 = Sha256File(Full(root, AdjudicationRoot + "/review-item-manifest.json")),
            expectedItems = bindings.Count,
            completedItems = 0,
            blankItems = bindings.Count,
            unresolvedItems = 0,
            responseFilePresent = false,
            frozen = false,
            modelPredictionReadCount = 0,
            providerResponseReadCount = 0,
            existingGoldReadCount = 0,
            modelCalls = 0,
            providerCalls = 0,
            note = "No human response file was supplied. No labels were generated by Codex or an LLM.",
        });
        WriteJson(Path.Combine(output, "firewall.json"), new
        {
            schemaVersion = "a99-v4h-b-firewall-v1",
            status = "V4H_ADJUDICATION_INCOMPLETE",
            authority = "BLINDED_SOURCE_BACKED_USER_ADJUDICATION",
            modelPredictionReadCount = 0,
            providerResponseReadCount = 0,
            existingGoldReadCount = 0,
            modelCalls = 0,
            providerCalls = 0,
            forbiddenInputsRead = Array.Empty<string>(),
        });
        File.WriteAllText(Path.Combine(output, "report.md"), BuildIncompleteReport(bindings.Count), new UTF8Encoding(false));
        Console.WriteLine($"STATUS=V4H_ADJUDICATION_INCOMPLETE EXPECTED={bindings.Count} COMPLETED=0 MODEL_CALLS=0 PROVIDER_CALLS=0");
        return 0;
    }

    private static int Validate(string root, string? responsePath)
    {
        if (string.IsNullOrWhiteSpace(responsePath)) return Fail("V4H_B_RESPONSE_PATH_REQUIRED");
        var bindings = LoadBindings(root);
        var responses = LoadResponses(Resolve(root, responsePath));
        var result = AdjudicationValidator.ValidateSet(responses, bindings, requireComplete: false);
        if (!result.IsValid)
        {
            foreach (var error in result.Errors) Console.Error.WriteLine(error);
            return Fail("V4H_B_RESPONSE_INVALID");
        }
        Console.WriteLine($"VALID=true RESPONSES={responses.Count} COMPLETE={responses.Select(x => x.ReviewId).Distinct(StringComparer.Ordinal).Count() == bindings.Count} MODEL_CALLS=0 PROVIDER_CALLS=0");
        return 0;
    }

    private static int Freeze(string root, string? responsePath)
    {
        if (string.IsNullOrWhiteSpace(responsePath)) return Fail("V4H_B_RESPONSE_PATH_REQUIRED");
        var bindings = LoadBindings(root);
        var responses = LoadResponses(Resolve(root, responsePath));
        var result = AdjudicationValidator.ValidateSet(responses, bindings, requireComplete: true);
        if (!result.IsValid)
        {
            foreach (var error in result.Errors.Take(20)) Console.Error.WriteLine(error);
            return Fail("V4H_B_FREEZE_BLOCKED_INCOMPLETE_OR_INVALID");
        }
        var output = Full(root, ResultsRelative);
        Directory.CreateDirectory(output);
        var frozenPath = Path.Combine(output, "human-adjudication.frozen.v1.json");
        if (File.Exists(frozenPath)) return Fail("V4H_B_FREEZE_IMMUTABLE");
        var canonical = responses.OrderBy(x => ReviewNumber(x.ReviewId)).ThenBy(x => x.ReviewId, StringComparer.Ordinal).ToArray();
        var frozen = new
        {
            schemaVersion = "a99-v4h-b-human-adjudication-frozen-v1",
            status = "BLINDED_SOURCE_BACKED_USER_ADJUDICATION_FROZEN",
            independentHumanGold = false,
            modelOutputsVisibleDuringReview = false,
            existingGoldVisibleDuringReview = false,
            itemCount = canonical.Length,
            relationCounts = canonical.GroupBy(x => x.Relation, StringComparer.Ordinal).ToDictionary(x => x.Key, x => x.Count(), StringComparer.Ordinal),
            confidenceCounts = canonical.GroupBy(x => x.Confidence, StringComparer.Ordinal).ToDictionary(x => x.Key, x => x.Count(), StringComparer.Ordinal),
            unresolvedCount = canonical.Count(x => x.Relation == "UNRESOLVED"),
            reviewItemManifestSha256 = Sha256File(Full(root, AdjudicationRoot + "/review-item-manifest.json")),
            responses = canonical,
        };
        var frozenJson = Serialize(frozen);
        File.WriteAllText(frozenPath, frozenJson, new UTF8Encoding(false));
        File.Copy(Resolve(root, responsePath), Path.Combine(output, "human-adjudication.responses.json"), overwrite: false);
        WriteJson(Path.Combine(output, "adjudication-summary.json"), new { status = "BLINDED_SOURCE_BACKED_USER_ADJUDICATION_FROZEN", itemCount = canonical.Length, unresolvedCount = canonical.Count(x => x.Relation == "UNRESOLVED"), frozenSha256 = Sha256Text(frozenJson) });
        WriteJson(Path.Combine(output, "firewall.json"), new { status = "BLINDED_SOURCE_BACKED_USER_ADJUDICATION_FROZEN", modelPredictionReadCount = 0, providerResponseReadCount = 0, existingGoldReadCount = 0, modelCalls = 0, providerCalls = 0 });
        Console.WriteLine($"STATUS=READY_FOR_V4H_SEMANTIC_ACCURACY_EVALUATION ITEMS={canonical.Length} FROZEN_SHA256={Sha256Text(frozenJson)} MODEL_CALLS=0 PROVIDER_CALLS=0");
        return 0;
    }

    private static Dictionary<string, FrozenReviewBinding> LoadBindings(string root)
    {
        var path = Full(root, AdjudicationRoot + "/review-item-manifest.json");
        using var document = JsonDocument.Parse(File.ReadAllText(path));
        var result = document.RootElement.GetProperty("items").EnumerateArray().Select(item => new FrozenReviewBinding(
            item.GetProperty("reviewId").GetString()!, item.GetProperty("candidateId").GetString()!,
            item.GetProperty("leftOccurrenceId").GetString()!, item.GetProperty("rightOccurrenceId").GetString()!,
            item.GetProperty("sourceBindingSha256").GetString()!)).ToArray();
        if (result.Length != ExpectedCount || result.Select(x => x.ReviewId).Distinct(StringComparer.Ordinal).Count() != ExpectedCount) throw new InvalidDataException("V4H_A_BINDING_MANIFEST_NOT_128_UNIQUE");
        return result.ToDictionary(x => x.ReviewId, StringComparer.Ordinal);
    }

    private static List<HumanReviewResponse> LoadResponses(string path)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(path));
        var rows = document.RootElement.ValueKind == JsonValueKind.Array ? document.RootElement.EnumerateArray() : document.RootElement.GetProperty("responses").EnumerateArray();
        return rows.Select(x => JsonSerializer.Deserialize<HumanReviewResponse>(x.GetRawText(), AdjudicationJson.Options) ?? throw new InvalidDataException("V4H_B_NULL_RESPONSE")).ToList();
    }

    private static string BuildIncompleteReport(int count) => string.Join(Environment.NewLine, new[]
    {
        "# V4H-B — blinded source-backed human adjudication",
        "",
        "Status: `V4H_ADJUDICATION_INCOMPLETE`",
        "",
        $"The immutable V4H-A pack contains `{count}` source-bound review items. No human response file was supplied in this execution, so no relation label was generated or inferred.",
        "",
        "## Firewall",
        "",
        "- Model predictions read: `0`",
        "- Provider responses read: `0`",
        "- Existing identity Gold read: `0`",
        "- Model calls: `0`",
        "- Provider calls: `0`",
        "",
        "## Gate",
        "",
        "`AWAITING_HUMAN_INPUT` → `V4H_ADJUDICATION_INCOMPLETE`",
        "",
        "Supply a human-authored `responses` JSON file to the V4H-B validator. `UNRESOLVED` is a valid human judgment; blank rows are not.",
        "",
        $"The final frozen artifact and semantic accuracy evaluation are intentionally not created until all `{count}` bindings have valid human responses.",
        "",
    });

    private static int ReviewNumber(string id) => int.TryParse(id.Split('-').LastOrDefault(), out var value) ? value : int.MaxValue;
    private static string Resolve(string root, string path)
    {
        var fullPath = Path.GetFullPath(Path.IsPathRooted(path) ? path : Path.Combine(root, path));
        var normalized = fullPath.Replace('\\', '/').ToLowerInvariant();
        var forbiddenMarkers = new[] { "/v4g-b", "/v4g-c", "/v4f-e", "/v4f-f", "/semantic-audit/", "/identity-gold/", "/predictions/" };
        if (forbiddenMarkers.Any(normalized.Contains)) throw new InvalidDataException("V4H_B_FORBIDDEN_INPUT_PATH");
        return fullPath;
    }
    private static string Full(string root, string relative) => Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar));
    private static string Serialize(object value) => JsonSerializer.Serialize(value, AdjudicationJson.Options) + Environment.NewLine;
    private static void WriteJson(string path, object value) => File.WriteAllText(path, Serialize(value), new UTF8Encoding(false));
    private static string Sha256File(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant();
    private static string Sha256Text(string text) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text))).ToLowerInvariant();
    private static int Fail(string message) { Console.Error.WriteLine(message); return 2; }
}
